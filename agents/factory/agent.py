#!/usr/bin/env python3
"""Factory Agent: GitHub Issue → Angular Component + PR."""

import json
import os
import re
import sys
from pathlib import Path

import anthropic
from github import Github, GithubException


def load_context() -> str:
    ctx = Path(__file__).parent.parent.parent / "context" / "meridian-coding-standards.md"
    return ctx.read_text(encoding="utf-8")


def pascal_to_kebab(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower()


def generate_component(title: str, body: str, standards: str) -> dict:
    client = anthropic.Anthropic(api_key=os.environ["ANTHROPIC_API_KEY"])

    prompt = f"""You are an Angular 18 expert on the Meridian Retail project.

## Meridian Coding Standards
{standards}

## Feature Specification
Title: {title}

{body}

## Task
Generate a complete Angular 18 standalone component. Return ONLY a valid JSON object with:
- "component_name": PascalCase (e.g. "ProductTile")
- "selector": kebab-case (e.g. "app-product-tile")
- "files": object with keys:
  - "component.ts": full TypeScript standalone component
  - "component.html": full HTML template
  - "component.scss": SCSS using Meridian design tokens ($color-*, $spacing-*)
  - "component.spec.ts": Jest/Jasmine unit tests covering all @Input() and public methods
  - "index.ts": barrel export

Rules:
- Use standalone: true, ChangeDetectionStrategy.OnPush
- All configurable values must be @Input() — no hardcoded strings
- SCSS must use design tokens, never raw hex
- spec.ts must import ComponentFixture and test at least 3 cases
- No markdown fences, just the JSON object"""

    message = client.messages.create(
        model="claude-sonnet-4-6",
        max_tokens=4096,
        messages=[{"role": "user", "content": prompt}],
    )

    raw = message.content[0].text.strip()
    # Strip accidental markdown fences if the model adds them
    raw = re.sub(r"^```(?:json)?\n?", "", raw)
    raw = re.sub(r"\n?```$", "", raw)
    return json.loads(raw)


def create_pr(repo, issue_number: int, component: dict) -> str:
    kebab = pascal_to_kebab(component["component_name"])
    branch = f"ai/component-{kebab}-i{issue_number}"
    base_path = f"src/app/components/{kebab}"

    # Create branch from default
    default = repo.get_branch(repo.default_branch)
    try:
        repo.create_git_ref(ref=f"refs/heads/{branch}", sha=default.commit.sha)
    except GithubException as e:
        if e.status == 422:  # branch already exists
            print(f"Branch {branch} already exists, reusing.")
        else:
            raise

    # Map file keys to actual filenames
    file_map = {
        "component.ts": f"{kebab}.component.ts",
        "component.html": f"{kebab}.component.html",
        "component.scss": f"{kebab}.component.scss",
        "component.spec.ts": f"{kebab}.component.spec.ts",
        "index.ts": "index.ts",
    }

    for key, filename in file_map.items():
        content = component["files"].get(key, "")
        if not content:
            continue
        path = f"{base_path}/{filename}"
        try:
            existing = repo.get_contents(path, ref=branch)
            repo.update_file(
                path=path,
                message=f"chore: regenerate {filename} (AI factory)",
                content=content,
                sha=existing.sha,
                branch=branch,
            )
        except GithubException:
            repo.create_file(
                path=path,
                message=f"feat: generate {filename} (AI factory)",
                content=content,
                branch=branch,
            )

    file_list = "\n".join(f"- `{base_path}/{fn}`" for fn in file_map.values())
    pr = repo.create_pull(
        title=f"feat({kebab}): {component['component_name']} component [AI generated]",
        body=f"""## AI-Generated Angular Component

Generated by **Meridian Angular AI Factory** from issue #{issue_number}.

### `<{component['selector']}>`

**Files:**
{file_list}

### Review checklist
- [ ] Component structure follows Meridian standards
- [ ] Unit tests cover main paths and @Input() variations
- [ ] No hardcoded values — uses @Input() or services
- [ ] SCSS uses Meridian design tokens
- [ ] Accessibility attributes present (aria-*)

> Opened automatically. The Review Agent will analyze this PR next.

Closes #{issue_number}""",
        head=branch,
        base=repo.default_branch,
    )
    pr.add_to_labels("ai-generated")

    issue = repo.get_issue(issue_number)
    issue.create_comment(
        f":robot: AI Factory opened PR #{pr.number}: {pr.html_url}"
    )
    print(f"PR created: {pr.html_url}")
    return pr.html_url


def main() -> None:
    token = os.environ["GITHUB_TOKEN"]
    issue_number = int(os.environ["ISSUE_NUMBER"])
    repo_name = os.environ["REPO_NAME"]

    gh = Github(token)
    repo = gh.get_repo(repo_name)
    issue = repo.get_issue(issue_number)

    standards = load_context()
    component = generate_component(issue.title, issue.body or "", standards)
    create_pr(repo, issue_number, component)


if __name__ == "__main__":
    main()
